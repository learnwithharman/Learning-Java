// Simple class
class Person {

    // method of class
    void sayHello() {
        System.out.println("Hello, I am a person.");
    }
}

// Main class
public class PersonClass {

    public static void main(String[] args) {

        // Creating object of Person class
        Person p1 = new Person();

        // Calling method using object
        p1.sayHello();
    }
}
